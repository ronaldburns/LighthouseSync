"""Writes src/dashboard/fonts_data.h from third_party/fonts/*.ttf (the dashboard's fonts, built into the exe).

The TTFs are IBM Plex (SIL OFL 1.1, third_party/fonts/OFL.txt), cut down to Latin with fontTools:
  pyftsubset IBMPlexSans-Regular.woff --unicodes=... --no-hinting --layout-features='' --flavor= --output-file=...
Run it after changing a font: python lhs/embed_fonts.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = ["IBMPlexSans-Regular", "IBMPlexSans-Medium", "IBMPlexSans-SemiBold", "IBMPlexMono-Regular"]

out = ["// generated by lhs/embed_fonts.py from third_party/fonts (IBM Plex, SIL OFL 1.1): don't edit", "#pragma once", ""]
for name in FONTS:
    data = open(os.path.join(ROOT, "third_party", "fonts", name + ".ttf"), "rb").read()
    ident = "k" + re.sub(r"[^A-Za-z0-9]", "", name)
    out.append("static const unsigned char %s[%d] = {" % (ident, len(data)))
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append("")
path = os.path.join(ROOT, "src", "dashboard", "fonts_data.h")
with open(path, "w", newline="\n") as f:
    f.write("\n".join(out))
print("wrote", path)
